// Generate the C++ parameter table and the factory presets from the Seance sources (src/engine.js, src/ui.js).
'use strict';
var path = require('path'), fs = require('fs'), src = process.argv[2], dir = process.argv[3];
var M = require(path.join(src, 'engine.js'));
var ui = fs.readFileSync(path.join(src, 'ui.js'), 'utf8');
var PRESETS = eval('(' + /var PRESETS = (\{[\s\S]*?\n  \});/.exec(ui)[1] + ')');
function cname(id) { return 'P_' + id.replace(/([a-z])([A-Z])/g, '$1_$2').replace(/\./g, '_').toUpperCase(); }
function num(x) { var s = String(x); return /[.e]/.test(s) ? s : s + '.0'; }
function str(s) { return JSON.stringify(String(s)); }
var P = M.HE_PARAMS, S = M.HE_SOURCES, out = [];
out.push('// Generated by gen.js from src/engine.js and src/ui.js (seance-ui). Do not edit by hand.', '#pragma once', 'namespace he {', '');
out.push('enum Param : int {');
P.forEach(function (p, i) { out.push('  ' + cname(p.id) + ' = ' + i + ','); });
out.push('  NPARAM = ' + P.length, '};', '');
out.push('struct ParamInfo { const char* id; const char* label; double min, max, def; bool exp, isInt, sw; int nEnum; const char* enums[8]; const char* unit; bool channel, bi, off; };');
out.push('static const ParamInfo PARAMS[NPARAM] = {');
P.forEach(function (p) {
  var en = p.en || [], e8 = []; for (var i = 0; i < 8; i++) e8.push(i < en.length ? str(en[i]) : 'nullptr');
  out.push('  { ' + [str(p.id), str(p.label), num(p.min), num(p.max), num(p.def), p.exp ? 'true' : 'false', p.int ? 'true' : 'false', p.sw ? 'true' : 'false', en.length, '{' + e8.join(', ') + '}', str(p.unit || ''), p.grp ? 'true' : 'false', p.bi ? 'true' : 'false', p.off ? 'true' : 'false'].join(', ') + ' },');
});
out.push('};', '');
out.push('static const int NSRC = ' + S.length + ';');
out.push('static const char* const SOURCES[NSRC] = {' + S.map(str).join(', ') + '};');
['level', 'pan', 'rev', 'spr', 'hsend', 'drive', 'hold', 'mute', 'tune', 'cents', 'matOff', 'distOff'].forEach(function (k) {
  out.push('static const int SRC_' + k.toUpperCase() + '[NSRC] = {' + S.map(function (s) { var id = s + '.' + k, has = P.some(function (p) { return p.id === id; }); return has ? cname(id) : '-1'; }).join(', ') + '};');
});
out.push('', '}  // namespace he', '');
fs.writeFileSync(path.join(dir, 'he_params.gen.h'), out.join('\n'));
var o2 = ['// Generated by gen.js from src/ui.js (seance-ui). Do not edit by hand.', '#pragma once', '#include "he_params.gen.h"', 'namespace he {', '',
  'struct PresetValue { int param; double value; };', 'struct Preset { const char* name; int n; const PresetValue* values; };', ''], list = [];
Object.keys(PRESETS).forEach(function (n, k) {
  var vals = PRESETS[n], keys = Object.keys(vals);
  keys.forEach(function (id) { if (!P.some(function (p) { return p.id === id; })) throw new Error('unknown param ' + id); });
  o2.push('static const PresetValue PRESET_' + k + '[] = {' + (keys.length ? keys.map(function (id) { return '{' + cname(id) + ', ' + num(vals[id]) + '}'; }).join(', ') : '{-1, 0.0}') + '};');
  list.push('  {' + str(n) + ', ' + keys.length + ', PRESET_' + k + '},');
});
o2.push('', 'static const int NPRESET = ' + list.length + ';', 'static const Preset PRESETS[NPRESET] = {'); o2 = o2.concat(list); o2.push('};', '', '}  // namespace he', '');
fs.writeFileSync(path.join(dir, 'he_presets.gen.h'), o2.join('\n'));
console.log(P.length + ' params, ' + list.length + ' presets');
